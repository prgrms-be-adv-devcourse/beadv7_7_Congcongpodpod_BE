INSERT INTO public.settlement_details (
    settlement_id, order_id, sales_amount, fee_rate, fee_amount,
    settlement_amount, order_completed_at, created_at
)
SELECT
    (orders.store_id - 1) * 100
        + ((extract(year FROM age(date_trunc('month', current_timestamp) - interval '1 month', date_trunc('month', orders.created_at))) * 12
            + extract(month FROM age(date_trunc('month', current_timestamp) - interval '1 month', date_trunc('month', orders.created_at))))::bigint + 1),
    orders.id,
    orders.total_price::bigint,
    0.0500,
    floor(orders.total_price * 0.05)::bigint,
    orders.total_price::bigint - floor(orders.total_price * 0.05)::bigint,
    orders.pickup_result_at,
    orders.pickup_result_at
FROM public.orders orders
WHERE orders.status = 'PICKED_UP';

INSERT INTO public.levels (member_id, dish_level, purchase_count, discount_amount, updated_at)
SELECT member_id, 'LEVEL_5', count(*)::integer, 0, current_timestamp
FROM public.orders
WHERE status = 'PICKED_UP'
GROUP BY member_id;


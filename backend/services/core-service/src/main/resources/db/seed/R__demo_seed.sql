WITH months AS (
    SELECT
        stores.store_id,
        month_no,
        date_trunc('month', current_timestamp) - month_no * interval '1 month' AS period_start
    FROM generate_series(1, 300) AS stores(store_id)
    CROSS JOIN generate_series(1, 100) AS month_numbers(month_no)
), aggregates AS (
    SELECT
        months.store_id,
        months.month_no,
        months.period_start,
        months.period_start + interval '1 month' AS period_end,
        count(orders.id)::bigint AS total_order_count,
        coalesce(sum(orders.total_price), 0)::bigint AS gross_amount
    FROM months
    LEFT JOIN public.orders orders
        ON orders.store_id = months.store_id
        AND orders.status = 'PICKED_UP'
        AND orders.created_at >= months.period_start
        AND orders.created_at < months.period_start + interval '1 month'
    GROUP BY months.store_id, months.month_no, months.period_start
)

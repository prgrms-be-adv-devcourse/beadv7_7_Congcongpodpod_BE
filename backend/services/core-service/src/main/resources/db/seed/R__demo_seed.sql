WITH events AS (
    SELECT
        member_id,
        id AS order_id,
        'USE'::varchar AS type,
        total_price AS amount,
        -total_price AS delta,
        created_at,
        0 AS event_order
    FROM public.orders
    UNION ALL
    SELECT
        member_id,
        id,
        'REFUND',
        total_price,
        total_price,
        created_at + interval '1 minute',
        1
    FROM public.orders
    WHERE status IN ('CANCELLED', 'REJECTED')
), balanced AS (
    SELECT
        events.*,
        charges.charge_amount
            + sum(delta) OVER (
                PARTITION BY events.member_id
                ORDER BY events.created_at, events.order_id, event_order
                ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
            ) AS balance_after
    FROM events
    JOIN demo_member_charge charges USING (member_id)
)
